-- ===========================================================================
-- 005 — Скрытие результатов голосования от зрителей.
-- Флажок в админке: пока включён, публичные REST-ответы и realtime-обновления
-- возвращают участников без голосов и процентов (закрытое голосование).
-- Администратор раскрывает итоги в нужный момент, сняв флажок.
-- ===========================================================================

ALTER TABLE events
  ADD COLUMN IF NOT EXISTS votes_hidden BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN events.votes_hidden IS
  'TRUE — результаты скрыты от зрителей: публичные ответы и realtime-обновления зануляют цифры, администратор видит голоса как обычно.';
