-- ===========================================================================
-- 004 — Фактический старт таймера голосования.
-- Длительность должна отсчитываться от момента перевода дебата в `active`,
-- а не от запланированного времени: администратор может запустить дебат
-- позже расписания.
-- ===========================================================================

ALTER TABLE events
  ADD COLUMN IF NOT EXISTS voting_started_at TIMESTAMPTZ;

COMMENT ON COLUMN events.voting_started_at IS
  'Фактический момент запуска активного голосования; NULL для upcoming и при выключенном таймере.';
